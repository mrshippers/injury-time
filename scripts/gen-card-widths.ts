/**
 * Writes src/lib/card/geist-widths.ts: the advance width of every Latin-1
 * character in Geist Regular, the font next/og's ImageResponse renders with
 * when given none. The season card's fit maths then measures text with the
 * same metrics the renderer uses, instead of guessing an average.
 *
 *   npx tsx scripts/gen-card-widths.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ttf = readFileSync(join(process.cwd(), "node_modules/next/dist/compiled/@vercel/og/Geist-Regular.ttf"));
const u16 = (o: number) => ttf.readUInt16BE(o);
const tables = new Map<string, number>();
for (let i = 0, n = u16(4); i < n; i += 1) {
  const rec = 12 + i * 16;
  tables.set(ttf.toString("latin1", rec, rec + 4), ttf.readUInt32BE(rec + 8));
}
const head = tables.get("head")!;
const hhea = tables.get("hhea")!;
const hmtx = tables.get("hmtx")!;
const cmap = tables.get("cmap")!;
const unitsPerEm = u16(head + 18);
const nMetrics = u16(hhea + 34);
const advance = (glyph: number) => u16(hmtx + 4 * Math.min(glyph, nMetrics - 1));

// cmap: the Windows Unicode BMP subtable, format 4
let sub = -1;
for (let i = 0, n = u16(cmap + 2); i < n; i += 1) {
  const rec = cmap + 4 + i * 8;
  const platform = u16(rec);
  const encoding = u16(rec + 2);
  const off = cmap + ttf.readUInt32BE(rec + 4);
  if (u16(off) === 4 && ((platform === 3 && encoding === 1) || platform === 0)) sub = off;
}
if (sub < 0) throw new Error("no format-4 cmap");
const segs = u16(sub + 6) / 2;
const ends = sub + 14;
const starts = ends + segs * 2 + 2;
const deltas = starts + segs * 2;
const ranges = deltas + segs * 2;
function glyphOf(code: number): number {
  for (let s = 0; s < segs; s += 1) {
    const end = u16(ends + s * 2);
    if (code > end) continue;
    const start = u16(starts + s * 2);
    if (code < start) return 0;
    const delta = ttf.readInt16BE(deltas + s * 2);
    const ro = u16(ranges + s * 2);
    if (ro === 0) return (code + delta) & 0xffff;
    const g = u16(ranges + s * 2 + ro + (code - start) * 2);
    return g === 0 ? 0 : (g + delta) & 0xffff;
  }
  return 0;
}

const widths: Record<number, number> = {};
for (let c = 32; c <= 255; c += 1) {
  const g = glyphOf(c);
  if (g) widths[c] = advance(g);
}
const widest = Math.max(...Object.values(widths));
const out = `// Generated by scripts/gen-card-widths.ts from next's bundled Geist-Regular.ttf (SIL OFL 1.1). Do not edit.
// Advance widths in font units; ${unitsPerEm} units = 1 em. Characters missing here measure as the widest (${widest}).
export const GEIST_UNITS_PER_EM = ${unitsPerEm};
export const GEIST_WIDEST = ${widest};
export const GEIST_WIDTHS: Readonly<Record<number, number>> = ${JSON.stringify(widths)};
`;
writeFileSync(join(process.cwd(), "src/lib/card/geist-widths.ts"), out);
console.log(`${Object.keys(widths).length} characters, ${unitsPerEm} units/em, W=${widths[87]} i=${widths[105]} space=${widths[32]}`);
