// returner: injured 55d ago, fit again 25d ago
lines.push(`insert into public.availability_events (club_id, player_id, status, noted_on) values (cid, ${idx(18)}, 'injured', ${q(iso(55))});`);
lines.push(`insert into public.availability_events (club_id, player_id, status, noted_on) values (cid, ${idx(18)}, 'fit', ${q(iso(25))});`);
// current: Bobby injured (link latest injury), Liam doubt, Kofi suspended
